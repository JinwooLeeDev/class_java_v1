package ch03;

public class ConstantTest3 {
    // 코드 실행의 시작점
    public static void main(String[] args) {
        // 사각형의 면적을 구하는 코드를 작성해 보세요. 단 상수 활용
        final int width = 5;
        System.out.println("한 변의 길이가 " + width + "인 정사각형의 넓이는 " + width * width + "입니다.");

        final int height = 10;
        System.out.println("가로의 길이가 " + width + "이고 세로의 길이가 " + height + "인 사각형의 넓이는 " + width * height + "입니다.");

    } // end of main

} // end of class


